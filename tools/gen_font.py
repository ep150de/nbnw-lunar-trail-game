"""
Lunar Trail bitmap font generator.

The font is authored here as ASCII art rather than shipped as a TTF for three
reasons:

  1. No build-time or run-time font dependency. The game always has text.
  2. Guaranteed pixel-exact rendering. A TTF goes through a rasteriser whose
     output changes with hinting settings and FreeType version; a hand-placed
     bitmap does not.
  3. Authentic. The Apple II original drew its text from hand-cut 7x8 character
     ROMs. This is the same idea, thirty years on.

Each glyph is 5 wide x 7 tall. Lowercase letters sit on rows 1-6 with descenders
reaching into row 6. A few private-use codepoints carry UI symbols the game
needs and that no text font should be asked to draw.

Outputs:
  assets/gen/font5x7.h        C++ lookup table (committed, so no Python needed)
  assets/gen/font5x7_preview.png   human-readable proof sheet

Run:  python3 tools/gen_font.py
"""

