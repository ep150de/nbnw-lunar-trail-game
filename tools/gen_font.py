# Correction: 'F' used a 6-wide glyph by mistake above.
GLYPHS['F'] = ("####.", "#....", "#....", "###..", "#....", "#....", "#....")

# Every printable ASCII char must be present.
for c in range(32, 127):
    ch = chr(c)
    if ch not in GLYPHS:
        raise SystemExit(f"missing ASCII glyph for {ch!r} (0x{c:02x})")


def encode(rows):
    """Rows of ASCII art -> 7 column bytes, bit 0 = top row."""
    cols = []
    for x in range(W):
        bits = 0
        for y, row in enumerate(rows):
            if x < len(row) and row[x] == '#':
                bits |= 1 << y
        cols.append(bits)
    return cols


def c_string_for(cp):
    """Escapes a codepoint for a C++ narrow string literal."""
    ch = chr(cp)
    if cp < 0x80:
        if ch in ('\\', '"'):
            return '\\' + ch
        if 0x20 <= cp < 0x7f:
            return ch
        return '\\%03o' % cp
    # Private-use area: emit the UTF-8 bytes directly as \xNN.
    utf8 = ch.encode('utf-8')
    return ''.join('\\x%02x' % b for b in utf8)


def emit_header(path):
    codes = sorted(ord(k) for k in GLYPHS)
    lines = []
    lines.append('// GENERATED FILE -- do not edit by hand.')
    lines.append('// Produced by tools/gen_font.py. Edit the ASCII art there instead.')
    lines.append('//')
    lines.append('// 5x7 bitmap font, column-encoded: one byte per column, bit 0 = top row.')
    lines.append('#pragma once')
    lines.append('')
    lines.append('#include <cstdint>')
    lines.append('')
    lines.append('namespace lt {')
    lines.append('')
    lines.append('constexpr int kGlyphW = %d;' % W)
    lines.append('constexpr int kGlyphH = %d;' % H)
    lines.append('// One pixel of advance between glyphs keeps 320x200 text readable.')
    lines.append('constexpr int kGlyphAdvance = %d;' % (W + 1))
    lines.append('')
    lines.append('struct GlyphDef {')
    lines.append('    uint32_t codepoint;')
    lines.append('    uint8_t cols[%d];' % W)
    lines.append('};')
    lines.append('')
    lines.append('inline constexpr GlyphDef kGlyphTable[] = {')
    for cp in codes:
        cols = encode(GLYPHS[chr(cp)])
        colstr = ', '.join('0x%02x' % b for b in cols)
        lines.append('    {0x%04xu, {%s}},  // %s' % (cp, colstr, repr(chr(cp))))
    lines.append('};')
    lines.append('')
    lines.append('inline constexpr int kGlyphCount = %d;' % len(codes))
    lines.append('')
    lines.append('}  // namespace lt')
    lines.append('')

    with open(path, 'w') as f:
        f.write('\n'.join(lines))
    return len(codes)


def emit_preview(path):
    try:
        from PIL import Image, ImageDraw
    except ImportError:
        print('PIL not available; skipping PNG proof sheet')
        return False

    # Render every glyph in a grid on a mid-grey background.
    cols = 16
    pad = 2
    cell_w = W + 3
    cell_h = H + 3
    rows = (len(GLYPHS) + cols - 1) // cols

    img = Image.new('RGB', (cols * cell_w * 8, rows * cell_h * 8), (0x18, 0x1a, 0x1f))
    d = ImageDraw.Draw(img)

    # 8x nearest upscale per pixel.
    def put(px, py, on):
        x0 = px * 8
        y0 = py * 8
        colour = (0xF2, 0xF2, 0xF2) if on else (0x18, 0x1a, 0x1f)
        d.rectangle([x0, y0, x0 + 7, y0 + 7], fill=colour)

    for idx, ch in enumerate(sorted(GLYPHS.keys())):
        gx = (idx % cols) * cell_w + pad
        gy = (idx // cols) * cell_h + pad
        cols_bits = encode(GLYPHS[ch])
        for x in range(W):
            bits = cols_bits[x]
            for y in range(H):
                put(gx + x, gy + y, (bits >> y) & 1)

    img.save(path)
    return True


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out_dir = os.path.join(root, 'assets', 'gen')
    os.makedirs(out_dir, exist_ok=True)

    n = emit_header(os.path.join(out_dir, 'font5x7.h'))
    print('wrote assets/gen/font5x7.h (%d glyphs)' % n)

    if emit_preview(os.path.join(out_dir, 'font5x7_preview.png')):
        print('wrote assets/gen/font5x7_preview.png')

    # Sanity: a rendered sample line, so obvious bit-order bugs are visible here.
    sample = "O2 94% | H2O 1,850 L | SEED 8A3F1C09"
    print('sample: ' + sample)
    for y in range(H):
        line = []
        for ch in sample:
            cols_bits = encode(GLYPHS.get(ch, GLYPHS['?']))
            for x in range(W):
                line.append('#' if (cols_bits[x] >> y) & 1 else '.')
            line.append(' ')
        print('  ' + ''.join(line))
    return 0


if __name__ == '__main__':
    sys.exit(main())
